/* Turns the edit list into CSS text — the same text goes into the live <style> and into the saved file.
   Regular declarations get !important: generated selectors (h1, .srow h3) are usually less specific than
   the site's own rules. Custom properties don't: they are written into the very selector that declares them,
   so the light/dark theme variants keep working. A selector "@media <cond>{<sel>}" is emitted inside that media block. */

import { googleUrl, usedFonts } from './fonts.js';

export const HEADER = '/* generated by JS-Art — edit with: node js-art/server.js */';

function block(sel, decls, indent = '') {
  const lines = decls.map(d => `${indent}  ${d.prop}: ${d.value}${d.weak || d.prop.startsWith('--') ? '' : ' !important'};`);
  return `${indent}${sel} {\n${lines.join('\n')}\n${indent}}\n`;
}

/* "@media <cond>{<sel>}": active = conditions the declaration sits in, inactive = conditions under which
   other rules redefine it (a dark theme) — the edit must not leak into those */
export function mediaSelector(selector, active, inactive) {
  const parts = [...active, ...inactive.map(c => `(not ${c})`)];
  return parts.length ? `@media ${parts.join(' and ')}{${selector}}` : selector;
}

/* imports: put the Google Fonts @import of the picked fonts first (the saved file); the live <style> loads
   fonts through <link> instead, because replacing an @import on every edit would flash the fallback font */
export function serialize(edits, { header = false, imports = false } = {}) {
  const groups = new Map();
  for (const { selector, prop, value, weak } of edits) {
    if (prop.startsWith('@')) continue; /* '@text' edits go into the HTML, not the stylesheet */
    if (!groups.has(selector)) groups.set(selector, []);
    const decls = groups.get(selector);
    /* 'filter:contrast' + 'filter:brightness' → one filter declaration */
    if (prop.startsWith('filter:')) {
      const fn = `${prop.slice(7)}(${value})`;
      const f = decls.find(d => d.prop === 'filter');
      if (f) f.value += ' ' + fn; else decls.push({ prop: 'filter', value: fn });
    } else if (prop.startsWith('translate:')) {
      /* 'translate:x' + 'translate:y' → one translate declaration; a missing axis stays 0 */
      let t = decls.find(d => d.prop === 'translate');
      if (!t) { t = { prop: 'translate', value: '', axes: ['0px', '0px'] }; decls.push(t); }
      t.axes[prop.endsWith('x') ? 0 : 1] = value;
      t.value = t.axes.join(' ');
    } else {
      decls.push({ prop, value, weak });
    }
  }
  const blocks = [...groups].map(([sel, decls]) => {
    const m = sel.match(/^@media\s*(.+?)\s*\{(.+)\}$/s);
    return m ? `@media ${m[1]} {\n${block(m[2], decls, '  ')}}\n` : block(sel, decls);
  });
  const url = imports ? googleUrl(usedFonts(edits)) : null;
  const body = (url ? [`@import url("${url}");\n`, ...blocks] : blocks).join('\n');
  if (!header) return body;
  return body ? `${HEADER}\n\n${body}` : HEADER + '\n';
}

export function scaleValue(declared, k) {
  const r = Math.round(k * 1000) / 1000;
  return r === 1 ? declared : `calc(${declared} * ${r})`;
}
