/* Turns the edit list into CSS text — the same text goes into the live <style> and into the saved file.
   Regular declarations get !important: generated selectors (h1, .srow h3) are usually less specific than
   the site's own rules. Custom properties don't: they are written into the very selector that declares them,
   so the light/dark theme variants keep working. A selector "@media <cond>{<sel>}" is emitted inside that media block. */

export const HEADER = '/* generated by JS-Art — edit with: node js-art/server.js */';

function block(sel, decls, indent = '') {
  const lines = decls.map(d => `${indent}  ${d.prop}: ${d.value}${d.prop.startsWith('--') ? '' : ' !important'};`);
  return `${indent}${sel} {\n${lines.join('\n')}\n${indent}}\n`;
}

export function serialize(edits, { header = false } = {}) {
  const groups = new Map();
  for (const { selector, prop, value } of edits) {
    if (!groups.has(selector)) groups.set(selector, []);
    const decls = groups.get(selector);
    /* 'filter:contrast' + 'filter:brightness' → one filter declaration */
    if (prop.startsWith('filter:')) {
      const fn = `${prop.slice(7)}(${value})`;
      const f = decls.find(d => d.prop === 'filter');
      if (f) f.value += ' ' + fn; else decls.push({ prop: 'filter', value: fn });
    } else {
      decls.push({ prop, value });
    }
  }
  const blocks = [...groups].map(([sel, decls]) => {
    const m = sel.match(/^@media\s*(.+?)\s*\{(.+)\}$/s);
    return m ? `@media ${m[1]} {\n${block(m[2], decls, '  ')}}\n` : block(sel, decls);
  });
  const body = blocks.join('\n');
  if (!header) return body;
  return body ? `${HEADER}\n\n${body}` : HEADER + '\n';
}

export function scaleValue(declared, k) {
  const r = Math.round(k * 1000) / 1000;
  return r === 1 ? declared : `calc(${declared} * ${r})`;
}
