import test from 'node:test';
import assert from 'node:assert/strict';
import { FONTS, findFont, firstFamily, fontStack, fontOf, googleUrl, usedFonts } from '../client/fonts.js';
import { serialize } from '../client/css-writer.js';
import { same } from '../client/actions.js';

test('the catalog has 20–30 unique fonts', () => {
  assert.ok(FONTS.length >= 20 && FONTS.length <= 30);
  assert.equal(new Set(FONTS.map(f => f.name)).size, FONTS.length);
});

test('firstFamily and fontOf read a font-family value', () => {
  assert.equal(firstFamily('"Open Sans", sans-serif'), 'Open Sans');
  assert.equal(firstFamily("'Lora', serif"), 'Lora');
  assert.equal(firstFamily('Georgia, serif'), 'Georgia');
  assert.equal(fontOf('"open sans", sans-serif').name, 'Open Sans');
  assert.equal(fontOf('Georgia, serif'), null);
});

test('fontStack adds the category as a fallback', () => {
  assert.equal(fontStack('Lora'), '"Lora", serif');
  assert.equal(fontStack('Roboto Mono'), '"Roboto Mono", monospace');
});

test('googleUrl builds one css2 request, skipping unknown names', () => {
  const u = googleUrl(['Inter', 'Lora', 'Nope', 'Inter']);
  assert.ok(u.startsWith('https://fonts.googleapis.com/css2?family=Inter:wght@100;200'));
  assert.ok(u.includes('&family=Lora:ital,wght@0,400;') && u.includes(';1,700'));
  assert.ok(u.endsWith('&display=swap'));
  assert.equal(googleUrl(['Nope']), null);
  assert.ok(googleUrl(['Open Sans']).includes('family=Open+Sans:'));
});

test('usedFonts finds catalog families among the edits', () => {
  const edits = [
    { selector: 'h1', prop: 'font-family', value: '"Lora", serif' },
    { selector: 'p', prop: 'font-family', value: 'Georgia, serif' },
    { selector: 'p', prop: 'font-weight', value: '700' },
    { selector: 'h2', prop: 'font-family', value: '"Lora", serif' },
  ];
  assert.deepEqual(usedFonts(edits), ['Lora']);
});

test('serialize puts the @import first only when asked', () => {
  const edits = [{ selector: 'h1', prop: 'font-family', value: '"Lora", serif' }];
  assert.ok(!serialize(edits).includes('@import'));
  const css = serialize(edits, { header: true, imports: true });
  assert.ok(css.indexOf('@import url("https://fonts.googleapis.com/css2?family=Lora') > css.indexOf('generated by'));
  assert.ok(css.indexOf('@import') < css.indexOf('h1 {'));
  assert.equal(serialize([{ selector: 'p', prop: 'color', value: 'red' }], { imports: true }), 'p {\n  color: red !important;\n}\n');
});

test('select values are the same only when equal', () => {
  assert.equal(same({ kind: 'select' }, 'italic', 'italic'), true);
  assert.equal(same({ kind: 'select' }, 'italic', 'normal'), false);
  assert.ok(findFont('inter'));
});

test('previewUrl is one request for the whole catalog with a glyph subset', async () => {
  const { previewUrl, previewFamily, parsePreview, FONTS: all } = await import('../client/fonts.js');
  const u = previewUrl();
  assert.equal((u.match(/family=/g) || []).length, all.length);
  assert.ok(u.includes('&text=') && u.includes('family=Open+Sans:wght@400') && u.endsWith('&display=swap'));
  assert.ok(u.length < 3500);
  assert.equal(previewFamily('Lora'), '"jsa-Lora", serif');
});

test('parsePreview reads family, file and unicode-range of each face', async () => {
  const { parsePreview } = await import('../client/fonts.js');
  const css = "@font-face {\n  font-family: 'Inter';\n  src: url(https://x/y?kit=1&v=2) format('woff2');\n  unicode-range: U+41-42, U+410;\n}\n@font-face {\n  font-family: 'Lora';\n  src: url(https://x/z) format('woff2');\n}";
  assert.deepEqual(parsePreview(css), [
    { family: 'Inter', url: 'https://x/y?kit=1&v=2', range: 'U+41-42, U+410' },
    { family: 'Lora', url: 'https://x/z', range: '' },
  ]);
});
